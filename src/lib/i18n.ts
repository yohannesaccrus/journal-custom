export const SUPPORTED_LOCALES = ["en", "fr", "id", "es"] as const;
export type Locale = (typeof SUPPORTED_LOCALES)[number];

/** Mirrors the /fr, /id, /es URL-prefix override already used for currency on
 * the Liquid teaser page (see jc-product-page.liquid) — any other locale
 * (or none) falls back to English, same as currency falls back to the
 * shop's real market for those. */
export function resolveLocale(lang?: string | null): Locale {
  const normalized = (lang ?? "").toLowerCase();
  return (SUPPORTED_LOCALES as readonly string[]).includes(normalized) ? (normalized as Locale) : "en";
}

